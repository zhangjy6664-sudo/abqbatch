@dataclass(frozen=True)
class ProjectConfig:
    """Resolved project paths and raw configuration dictionaries."""

    root: Path
    project: dict[str, Any]
    materials: dict[str, Any]
    loads: dict[str, Any]
    postprocess: dict[str, Any]

    @property
    def raw_inp_dir(self) -> Path:
        return self.root / self.project["paths"]["raw_inp"]

    @property
    def work_dir(self) -> Path:
        return self.root / self.project["paths"]["work"]

    @property
    def reports_dir(self) -> Path:
        return self.root / self.project["paths"]["reports"]

    @property
    def db_path(self) -> Path:
        return self.root / self.project["paths"]["database"]


def read_yaml(path: Path) -> dict[str, Any]:
    """Read a YAML mapping from disk."""

    if not path.exists():
        raise ConfigError(f"Missing configuration file: {path}")
    data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    if not isinstance(data, dict):
        raise ConfigError(f"Configuration must be a mapping: {path}")
    return data


def write_yaml(path: Path, data: dict[str, Any]) -> None:
    """Write a YAML mapping with stable key order."""

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(yaml.safe_dump(data, sort_keys=False), encoding="utf-8")


def load_project(project_root: Path) -> ProjectConfig:
    """Load all project-level YAML configuration files."""

    root = project_root.resolve()
    configs = root / "configs"
    project = yaml.safe_load(DEFAULT_PROJECT_YML) or {}
    project.update(read_yaml(configs / "project.yml"))
    materials = read_yaml(configs / "materials.yml")
    loads = read_yaml(configs / "load_schemes.yml")
    postprocess = read_yaml(configs / "postprocess.yml")
    return ProjectConfig(root, project, materials, loads, postprocess)


def project_relative(path: Path, root: Path) -> str:
    """Return a POSIX-style path relative to the project root when possible."""

    try:
        return path.resolve().relative_to(root.resolve()).as_posix()
    except ValueError:
        return path.as_posix()



