def _write_default_raw_inputs(root: Path) -> list[Path]:
    raw_dir = root / "raw_inp"
    if any(raw_dir.glob("*.inp")):
        return []
    files = {
        raw_dir / "model_001.inp": _default_inp_text("model_001", 1.0),
        raw_dir / "model_002.inp": _default_inp_text("model_002", 2.0),
    }
    for file_path, content in files.items():
        file_path.write_text(content, encoding="utf-8")
    return list(files)
def init_project(path: Path, force: bool = False) -> list[Path]:
    """Create a new abqbatch project layout and default YAML files."""

    root = path.resolve()
    created: list[Path] = []
    for dirname in ("configs", "raw_inp", "work", "reports", "db", "logs"):
        target = root / dirname
        target.mkdir(parents=True, exist_ok=True)
        created.append(target)

    defaults = {
        root / "configs" / "project.yml": DEFAULT_PROJECT_YML,
        root / "configs" / "materials.yml": DEFAULT_MATERIALS_YML,
        root / "configs" / "load_schemes.yml": DEFAULT_LOADS_YML,
        root / "configs" / "postprocess.yml": DEFAULT_POSTPROCESS_YML,
    }
    for file_path, content in defaults.items():
        if force or not file_path.exists():
            file_path.write_text(content, encoding="utf-8")
            created.append(file_path)
    created.extend(_write_default_raw_inputs(root))
    return created
